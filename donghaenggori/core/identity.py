"""발화에서 성함과 사는 곳을 뽑는다.

통화에서 "어르신 성함과 사시는 읍면동을 말씀해 주세요" 라고 물어놓고, 정작 그
답을 아무 데도 담지 않았다. 병원·날짜는 칸이 있는데 이름·주소는 원문에만 남아
복지사가 매번 원문을 읽어야 했다 — 물어본 이유가 화면에 없었다.

**여기서 뽑은 값은 언제나 '확인 필요' 다.** 확정으로 올리지 않는다:

  · 이름은 STT 오인식이 특히 잦다. 짧고, 사전에 없고, 8kHz 전화 음질이다.
    틀린 이름을 '확인됨' 으로 띄우면 복지사가 그대로 부르게 된다 — 사람을
    잘못 부르는 건 병원명을 틀리는 것과 다른 종류의 사고다.
  · 규칙으로 뽑는 이상 "저는 이영희고요" 같은 정형 발화만 잡힌다. 못 잡는
    경우가 많고, 그때는 조용히 비운다. 원문은 그대로 남으니 잃는 것이 없다.

목적은 '자동 등록' 이 아니라 **복지사가 원문을 안 읽어도 누군지 보이게** 하는
것이다. 확정은 사람이 한다.
"""
from __future__ import annotations

import re

# ── 사는 곳 ────────────────────────────────────────────────────────────────
#
# 읍면동은 규칙이 확실하다. 어르신은 "목포시 용당동", "신안군 압해읍" 처럼
# 시군구까지 붙여 말하기도 하고 "용당동" 만 말하기도 한다. 둘 다 받는다.
#
# 앞에 시/군/구가 붙으면 함께 잡는다 — 같은 이름의 동이 여러 시에 있어서
# ("중앙동" 은 전남에만 여럿) 시군구가 있으면 확인 전화가 훨씬 쉬워진다.
#
# '리' 는 뺐다. 통화에서 묻는 것이 읍면동이기도 하고, "허리·머리·다리·소리"
# 처럼 몸 이야기에 흔한 말이 전부 걸린다. "○○리" 를 얻는 것보다 "허리 아파서"
# 를 주소로 잡는 쪽이 훨씬 잦고 나쁘다.
_REGION_RE = re.compile(
    r"(?:([가-힣]{2,3}(?:시|군|구))\s*)?"      # 목포시 · 신안군 (없을 수도)
    r"([가-힣]{1,4}(?:읍|면|동))"              # 용당동 · 압해읍 · 하의면
)

# '동' 으로 끝나지만 사는 곳이 아닌 말들. "행동", "운동" 같은 것이 걸린다.
_NOT_A_REGION = {
    "행동", "운동", "활동", "이동", "출동", "작동", "감동", "충동", "자동",
    "수동", "공동", "합동", "노동", "부동", "가동", "발동", "진동",
    "면", "동", "리", "읍",                    # 접미사만 남은 경우
    "그동", "이동", "저동",
}


def detect_region(text: str) -> str | None:
    """발화에 나온 사는 곳. 없으면 None.

    "저는 목포시 용당동 삽니다"  → "목포시 용당동"
    "용당동 사는데요"            → "용당동"
    "운동 하다가 넘어졌어"        → None
    """
    for m in _REGION_RE.finditer(text):
        sigungu, dong = m.group(1), m.group(2)
        if dong in _NOT_A_REGION:
            continue
        return f"{sigungu} {dong}" if sigungu else dong
    return None


# ── 성함 ──────────────────────────────────────────────────────────────────
#
# 이름은 규칙으로 잡을 수 있는 형태가 제한적이다. 어르신이 이름을 말하는
# 방식은 대개 아래 몇 가지로 수렴한다.
#
#   "저는 이영희입니다"  "이영희예요"  "이영희라고 합니다"
#   "제 이름은 이영희"   "이영희인데요"  "이영희고요"
#
# 성 1자 + 이름 2자(가끔 1자·3자)를 기본으로 본다. 더 넓히면 "무릎이" 같은
# 일반 명사가 이름으로 잡힌다 — 못 잡는 쪽이 틀리게 잡는 쪽보다 낫다.
# 이름 뒤에 붙는 말. **긴 것부터** 본다 — 짧은 것이 먼저 걸리면 이름 쪽이
# 탐욕적으로 늘어난다. "저는 이영희고요" 에서 끝의 '요' 만 꼬리로 보면 이름이
# '이영희고' 가 되어 버렸다.
_NAME_TAIL = (r"입니다|이라고\s*합니다|라고\s*합니다|이라고\s*해요|라고\s*해요|"
              r"이라고요|이에요|이고요|인데요|이라고|예요|고요|인데|라고")

_NAME = r"([가-힣]{2,4}?)"          # 비탐욕 — 꼬리를 먼저 만족시킨다

_NAME_PATTERNS = (
    # "제 이름은 김말순입니다" — 꼬리가 없을 수도 있어 경계로 끊는다. 안 끊으면
    # 탐욕적으로 '김말순입' 까지 먹는다.
    re.compile(r"(?:제|내)\s*이름은\s*" + _NAME + rf"(?={_NAME_TAIL}|[\s,.]|$)"),
    re.compile(r"(?:저는|나는|저)\s*" + _NAME + rf"\s*(?:{_NAME_TAIL})"),
    re.compile(_NAME + rf"\s*(?:{_NAME_TAIL})"),
)

# 이름 자리에 와도 이름이 아닌 말. 위 패턴은 조사에 기대는데, 어르신 발화에는
# "저는 지금 아파요" 처럼 부사·명사가 그 자리에 오는 일이 흔하다.
_NOT_A_NAME = {
    "지금", "오늘", "내일", "모레", "어제", "여기", "저기", "거기", "이거",
    "그거", "저거", "무릎", "허리", "다리", "어깨", "머리", "가슴", "배가",
    "병원", "의원", "약국", "혼자", "그냥", "진짜", "정말", "많이", "조금",
    "아까", "이따", "요즘", "자꾸", "계속", "다시", "이제", "아직", "먼저",
    "사람", "어르신", "할머니", "할아버지", "아들", "딸이", "며느리",
}


def detect_name(text: str) -> str | None:
    """발화에 나온 성함. 없으면 None.

    "저는 이영희고요 목포시 용당동 삽니다"  → "이영희"
    "이영희라고 합니다"                    → "이영희"
    "저는 지금 무릎이 아파요"               → None
    """
    for pat in _NAME_PATTERNS:
        m = pat.search(text)
        if not m:
            continue
        name = m.group(1)
        if name in _NOT_A_NAME:
            continue
        return name
    return None
