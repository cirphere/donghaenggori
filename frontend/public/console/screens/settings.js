//
// 목업에는 기관명·연락처를 고치는 '수정' 링크와 알림 토글 3개가 있었는데
// **둘 다 넣지 않았다.**
//
// 수정: 기관 정보를 담을 테이블이 없다. 입력칸만 만들면 눌러서 고쳐 놓고
//       새로고침하면 되돌아간다 — 저장된 줄 알았다가 안 된 것을 나중에
//       발견하는 쪽이, 처음부터 못 고치는 것보다 나쁘다.
//
// 알림: 푸시·SMS 인프라가 아예 없다. 켜도 아무 일이 일어나지 않는다.
//       동작하지 않는 스위치를 두면 심사위원이 켜 보고 아무 반응이 없을 때
//       화면 전체를 의심하게 된다. 자리만 남기고 '준비 중'으로 적는다.

import { el, frow, sectionTitle } from "../ui.js";
import { state } from "../app.js";

export function renderSettings() {
  const u = state.user || {};
  return el("div", "wide-pane", [
    el("h1", "home-h1", "설정"),
    el("div", "home-sub", "지금은 확인만 할 수 있어요. 계정은 기관 운영자가 만듭니다."),

    sectionTitle("내 정보"),
    frow("이름", u.name),
    frow("역할", u.role),
    frow("아이디", u.id),
    frow("권한", (u.permissions || []).join(" · "), {
      evidence: ["화면에서 버튼을 가리는 기준이에요. 실제 차단은 서버가 합니다."],
    }),

    sectionTitle("알림", "준비 중 — 아직 동작하지 않아요"),
    ...[
      ["새 요청 알림", "전화·문자 요청이 들어오면 알려드려요"],
      ["긴급 요청 알림", "담당자 연결이 필요한 요청은 즉시 알려드려요"],
      ["기록 필요 알림", "동행 완료 후 사후기록이 없으면 다음 날 알려드려요"],
    ].map(([t, s]) => frow(t, s, { right: el("span", "badge plain", "준비 중") })),

    sectionTitle("보안"),
    frow("토큰 보관", "sessionStorage", {
      evidence: ["복지관 공용 PC라 탭을 닫으면 로그인이 풀립니다."],
    }),
    frow("외부 전송", "없음", {
      evidence: ["음성인식·의도분류·검색을 전부 기관 안에서 실행합니다.",
                 "어르신 발화가 외부 API로 나가지 않습니다."],
    }),
  ]);
}
